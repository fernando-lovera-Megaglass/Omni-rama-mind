// Local run of the scheduled marketing e-mails worker: PostgreSQL in WASM (PGlite), the real marketing-emails.sql
// and marketing-process.sql migrations, the real RPCs and the same processor the Edge Function uses. Gmail is
// mocked; no Supabase project, credentials, network or real e-mail. Run: npm run test:marketing-process
//
// Acceptance: a campaign with programado_para in the past becomes 'enviado' with enviado_at and enviados > 0;
// one with a future date is not touched. Also: drafts, snapshots of active segments, static segments, batches
// across ticks, per-recipient failures, cancellation in flight, the daily budget, a missing sender, idempotent
// migration, concurrent ticks and permissions.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { processDue, noRecipientsMessage } from '../supabase/functions/marketing-process/processor.mjs';

const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create table contacts(id bigint generated by default as identity primary key, name text default '', email text default '');
create table segments(id bigint generated by default as identity primary key, name text default '', object text default 'contacts', type text default 'active', member_ids jsonb not null default '[]');`);
await db.exec(await readFile(new URL('../supabase/activities.sql', import.meta.url), 'utf8'));
await db.exec(await readFile(new URL('../supabase/marketing-emails.sql', import.meta.url), 'utf8'));
const migration = await readFile(new URL('../supabase/marketing-process.sql', import.meta.url), 'utf8');
await db.exec(migration);
await db.exec(migration); // Migration is repeatable.
const query = async (sql, args = []) => (await db.query(sql, args)).rows;

await query(`insert into contacts(name, email) values ('Ana', 'ana@example.invalid'), ('Beto', 'beto@example.invalid'), ('Carla', 'carla@example.invalid'), ('Dani', '')`);
const [staticSeg] = await query(`insert into segments(name, type, member_ids) values ('Instaladores', 'static', '[2, 3, 4]') returning id`);
const [activeSeg] = await query(`insert into segments(name, type) values ('Clientes activos', 'active') returning id`);
const add = async (nombre, { estado = 'programado', at = '2020-01-01T00:00:00Z', destinatarios = { kind: 'all' }, de = 'hola@megaglass.us' } = {}) =>
  (await query(`insert into marketing_emails(nombre, asunto, de_nombre, de_email, html_content, estado, programado_para, destinatarios)
    values ($1, 'Asunto de ' || $1, 'Megaglass', $2, '<p>Hola</p>', $3, $4, $5) returning *`, [nombre, de, estado, at, JSON.stringify(destinatarios)]))[0];
const get = async (id) => (await query('select * from marketing_emails where id=$1', [id]))[0];
const runOf = async (id) => (await query('select * from marketing_email_runs where email_id=$1', [id]))[0];
const seededFuture = await get('c1000000-0000-4000-8000-000000000005'); // [Prueba] Felicitación de fin de año: programado, +20 días

const sends = [];
const sender = { id: 'acc-local', email: 'hola@megaglass.us' };
const store = {
  due: (now) => query('select * from marketing_due($1)', [now]),
  claim: async (id) => (await query('select * from marketing_claim($1)', [id]))[0],
  run: runOf,
  recipients: (id) => query('select * from marketing_recipients($1)', [id]),
  sentToday: async (now) => Number((await query("select coalesce(sum(sent), 0) as n from marketing_email_runs where updated_at >= date_trunc('day', $1::timestamptz)", [now]))[0].n),
  sender: async () => sender,
  reserve: async (e, index) => (await query('select marketing_progress($1, $2, null, null, null, null) as ok', [e.id, index]))[0].ok,
  progress: async (e, index, ok, error, person, receipt) => (await query('select marketing_progress($1, $2, $3, $4, $5, $6) as ok', [e.id, index, ok, error, person.contact_id, receipt == null ? null : JSON.stringify(receipt)]))[0].ok,
  finish: async (e, status, error = null) => (await query('select marketing_finish($1, $2, $3) as s', [e.id, status, error]))[0].s,
};
const send = async (e, account, person) => { assert.equal(account.email, 'hola@megaglass.us'); assert.match(person.email, /@/); sends.push(`${e.nombre}→${person.email}`); return { id: `mock-${sends.length}`, threadId: 't' }; };
const sentTo = (nombre) => sends.filter((s) => s.startsWith(`${nombre}→`)).map((s) => s.split('→')[1]);
const now = new Date();

// ===== 1) Acceptance: past → enviado (enviado_at, enviados > 0); future and draft untouched; concurrent ticks =====
const past = await add('Pasado');
const future = await add('Futuro', { at: '2099-01-01T00:00:00Z' });
const draft = await add('Borrador con fecha', { estado: 'borrador' });
const [r1, r2] = await Promise.all([processDue(store, send, now), processDue(store, send, now)]);
assert.deepEqual([...r1, ...r2].map((r) => r.status), ['sent']);
const sentPast = await get(past.id);
assert.equal(sentPast.estado, 'enviado');
assert.ok(sentPast.enviado_at, 'enviado_at set');
assert.equal(sentPast.enviados, 3);
assert.equal(sentPast.entregados, 3);
assert.ok(sentPast.enviados > 0);
assert.deepEqual(sentTo('Pasado'), ['ana@example.invalid', 'beto@example.invalid', 'carla@example.invalid']);
assert.deepEqual(await get(future.id), future, 'a future campaign is not touched');
assert.deepEqual(await get(draft.id), draft, 'a draft is never sent');
assert.deepEqual(await get(seededFuture.id), seededFuture, 'the seeded scheduled [Prueba] campaign stays scheduled');
assert.equal((await runOf(past.id)).status, 'done');
assert.equal((await runOf(past.id)).sent, 3);
const acts = await query("select record_id, type, text, who, extra from activities where extra->>'marketingEmailId' = $1 order by record_id", [past.id]);
assert.deepEqual(acts.map((a) => [Number(a.record_id), a.type, a.text, a.who, a.extra.opened, a.extra.channel]), [[1, 'email', 'Correo de marketing: Pasado', 'Marketing', false, 'Correo de marketing'], [2, 'email', 'Correo de marketing: Pasado', 'Marketing', false, 'Correo de marketing'], [3, 'email', 'Correo de marketing: Pasado', 'Marketing', false, 'Correo de marketing']]);
assert.equal(acts[0].extra.subject, 'Asunto de Pasado');
await processDue(store, send, now);
assert.equal(sends.length, 3, 'a sent campaign is never picked up again');

// ===== 2) Recipients: snapshot of an active segment, static segment by member_ids, active segment without snapshot =====
const snap = await add('Instantánea', { destinatarios: { kind: 'segment', id: String(activeSeg.id), ids: [1, 2, 4, 999], snapshotAt: now.toISOString(), senderAccountId: null } });
const stat = await add('Estático', { destinatarios: { kind: 'segment', id: String(staticSeg.id) } });
const noSnap = await add('Activo sin instantánea', { destinatarios: { kind: 'segment', id: String(activeSeg.id) } });
const r3 = await processDue(store, send, now);
assert.deepEqual(Object.fromEntries(r3.map((r) => [r.id, r.status])), { [snap.id]: 'sent', [stat.id]: 'sent', [noSnap.id]: 'error' });
assert.deepEqual(sentTo('Instantánea'), ['ana@example.invalid', 'beto@example.invalid'], 'snapshot ids, only contacts with e-mail');
assert.equal((await get(snap.id)).enviados, 2);
assert.deepEqual(sentTo('Estático'), ['beto@example.invalid', 'carla@example.invalid'], 'static segment: member_ids with e-mail');
assert.equal((await get(noSnap.id)).estado, 'programado', 'left for review');
assert.equal((await runOf(noSnap.id)).status, 'error');
assert.match((await runOf(noSnap.id)).last_error, /instantánea/);
assert.equal(noRecipientsMessage({ destinatarios: { kind: 'segment' } }), (await runOf(noSnap.id)).last_error);
const before = sends.length;
await processDue(store, send, now);
assert.equal(sends.length, before, 'an errored run is not retried blindly');

// ===== 3) Batches across ticks (perRun limit): partial → continues from next_index → sent, no duplicates =====
const big = await add('Lote');
const r4 = await processDue(store, send, now, { perRun: 2 });
assert.deepEqual(r4, [{ id: big.id, status: 'partial', processed: 2, total: 3 }]);
assert.equal((await get(big.id)).estado, 'programado');
assert.equal((await runOf(big.id)).next_index, 2);
assert.equal((await runOf(big.id)).sent, 2);
assert.equal((await runOf(big.id)).lease_until, null, 'lease released for the next tick');
const r5 = await processDue(store, send, now, { perRun: 2 });
assert.deepEqual(r5, [{ id: big.id, status: 'sent', processed: 3, total: 3 }]);
assert.equal((await get(big.id)).enviados, 3);
assert.deepEqual(sentTo('Lote'), ['ana@example.invalid', 'beto@example.invalid', 'carla@example.invalid']);

// ===== 4) A recipient fails: the campaign still finishes, the failure is counted and kept =====
const flaky = await add('Con fallo');
await processDue(store, async (e, a, p) => { if (p.email.startsWith('beto')) throw new Error('SMTP down'); return send(e, a, p); }, now);
assert.equal((await get(flaky.id)).estado, 'enviado');
assert.equal((await get(flaky.id)).enviados, 2);
assert.deepEqual([(await runOf(flaky.id)).sent, (await runOf(flaky.id)).failed, (await runOf(flaky.id)).last_error], [2, 1, 'SMTP down']);
assert.deepEqual(sentTo('Con fallo'), ['ana@example.invalid', 'carla@example.invalid']);

// ===== 5) Unscheduled while in flight: the app's state wins, no further sends =====
const cancelled = await add('Cancelado');
const r6 = await processDue(store, async (e, a, p) => { await query("update marketing_emails set estado='borrador' where id=$1", [e.id]); return send(e, a, p); }, now);
assert.equal(r6[0].status, 'cancelled');
assert.equal((await get(cancelled.id)).estado, 'borrador');
assert.equal((await runOf(cancelled.id)).status, 'cancelled');
assert.equal(sentTo('Cancelado').length, 1);

// ===== 6) Daily budget exhausted → deferred, untouched; missing sender → error for review =====
const deferred = await add('Diferido');
assert.deepEqual(await processDue(store, send, now, { daily: 1 }), [{ id: deferred.id, status: 'deferred' }]);
assert.deepEqual(await get(deferred.id), deferred);
assert.equal(await runOf(deferred.id), undefined);
const r7 = await processDue({ ...store, sender: async () => { throw new Error('No hay una cuenta de Gmail activa para el remitente'); } }, send, now);
assert.deepEqual(r7.map((r) => [r.id, r.status]), [[deferred.id, 'error']]);
assert.match((await runOf(deferred.id)).last_error, /cuenta de Gmail/);
assert.equal((await get(deferred.id)).estado, 'programado');

// ===== 7) Permissions: only the service role may run the RPCs =====
await db.exec('set role anon');
await assert.rejects(() => query('select * from marketing_claim($1)', [future.id]), /permission denied/);
await assert.rejects(() => query('select * from marketing_email_runs'), /permission denied/);
await db.close();
console.log(`PASS: past campaign → enviado (enviado_at, enviados=${sentPast.enviados}); future/draft/seeded untouched; snapshot, static and active-segment recipients; batches across ticks; failures; cancellation; daily budget; missing sender; permissions. Gmail mocked, no external calls.`);
