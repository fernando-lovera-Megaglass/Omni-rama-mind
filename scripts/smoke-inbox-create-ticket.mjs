// Local DOM smoke: conversation → ticket, associations, timelines and links. Network is blocked.
// Run: node scripts/smoke-inbox-create-ticket.mjs
import { JSDOM } from 'jsdom';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const log = (...a) => console.log('[inbox-create-ticket]', ...a);
const fail = (msg) => { console.error(`[inbox-create-ticket] FAIL: ${msg}`); process.exit(1); };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const mem = {};
const dom = new JSDOM('<!doctype html><body class="app"><aside id="sidenav"></aside><header id="topbar"></header><main class="content content--inbox" id="inbox-root"></main><div id="scrim"></div></body>', { url: 'http://localhost/inbox/', pretendToBeVisual: true });
for (const k of ['window', 'document', 'location', 'history', 'HTMLElement', 'Event', 'CustomEvent', 'KeyboardEvent', 'FormData', 'URL', 'Blob', 'MutationObserver']) globalThis[k] = dom.window[k];
globalThis.localStorage = { getItem: (k) => (k in mem ? mem[k] : null), setItem: (k, v) => { mem[k] = String(v); }, removeItem: (k) => { delete mem[k]; }, key: (i) => Object.keys(mem)[i] ?? null, get length() { return Object.keys(mem).length; } };
Object.defineProperty(globalThis, 'navigator', { value: { clipboard: { writeText() {} } }, configurable: true });
dom.window.HTMLElement.prototype.scrollIntoView = function () {};
dom.window.HTMLElement.prototype.scrollBy = function () {};
dom.window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
let networkCalls = 0;
globalThis.fetch = async () => { networkCalls += 1; throw new Error('network blocked in the test'); };
const $ = (id) => document.getElementById(id);
const q = (s) => document.querySelector(s);
const qa = (s) => [...document.querySelectorAll(s)];
const text = (el) => (el ? el.textContent.replace(/\s+/g, ' ').trim() : '');
const click = (el) => { if (!el) fail('missing element to click'); el.dispatchEvent(new window.MouseEvent('click', { bubbles: true, cancelable: true })); };
const submit = () => $('inbox-reply').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
const ctrlEnter = () => $('inbox-reply').elements.body.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, bubbles: true, cancelable: true }));

const data = await import(resolve(here, '../src/data.js'));
const Conv = await import(resolve(here, '../src/conversations-data.js'));
await Conv.ready;
const contact = data.allContacts().find((c) => c.companyId);
const conv = Conv.createConversation({ contactId: contact.id, subject: 'Soporte <urgente> & factura', body: 'Ayuda', channel: 'email', assignedTo: Conv.ASSIGNEES[1] });
const inbox = await import(resolve(here, '../src/inbox.js'));
inbox.state.activeId = conv.id; inbox.renderAll();
$('inbox-reply').elements.body.value = 'Borrador conservado';
click(q('[data-inbox="create-ticket"]'));
const f = $('ct-form').elements;
if (f.name.value !== conv.subject || f.source.value !== 'Correo' || f.owner.value !== conv.assignedTo) fail('conversation prefill');
const pipes = data.ticketPipelines();
if (f.pipeline.value !== pipes[0] || f.status.value !== data.firstOpenTicketStatus(pipes[0])) fail('pipeline defaults');
if (!q('#ct-contacts-list [data-ct="remove"]').disabled) fail('contact must stay associated');
f.pipeline.value = pipes[1]; f.pipeline.dispatchEvent(new Event('change', { bubbles: true }));
if (f.status.value !== data.firstOpenTicketStatus(pipes[1]) || [...f.status.options].map(o => o.value).join() !== data.ticketStatusesFor(pipes[1]).map(s => s[0]).join()) fail('pipeline status options');
const other = Conv.conversations().find(c => c.id !== conv.id);
inbox.state.activeId = other.id; inbox.renderAll();
$('ct-form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
$('ct-form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
await wait(60);
const tickets = data.allTickets().filter(t => t.name === conv.subject);
if (tickets.length !== 1) fail('one ticket despite double submit');
const ticket = tickets[0];
if (Number(ticket.contactId) !== Number(contact.id) || Number(ticket.companyId) !== Number(contact.companyId)) fail('contact/company association');
if (ticket.pipeline !== pipes[1] || ticket.status !== data.firstOpenTicketStatus(pipes[1])) fail('saved pipeline/status');
const activity = data.activitiesFor('tickets', ticket.id).find(a => a.text === `Ticket creado desde la conversación "${conv.subject}"`);
if (!activity || activity.extra.conversationId !== conv.id) fail('ticket timeline links origin');
const note = Conv.messagesOf(conv.id).find(m => m.body.includes(`../tickets/record/?id=${ticket.id}`));
if (!note || !Conv.isInternalNote(note) || Conv.messagesOf(other.id).some(m => m.id === note.id)) fail('internal note belongs to original conversation');
if (!data.activitiesFor('contacts', contact.id).some(a => a.extra?.conversationId === conv.id && a.extra?.internal)) fail('contact timeline');
if (!q(`#toast a[href="../tickets/record/?id=${ticket.id}"]`) || text(q('#toast a')) !== 'Ver ticket') fail('toast link');
inbox.state.activeId = conv.id; inbox.renderAll();
if (!q(`#inbox-messages .msg--note a[href="../tickets/record/?id=${ticket.id}"]`) || q('#inbox-messages urgente')) fail('thread escaped link');
if (!JSON.parse(mem['crm:conversation_messages']).some(m => m.id === note.id && m.body.includes(String(ticket.id)))) fail('note persistence');
const unassigned = Conv.createConversation({ contactId: contact.id, subject: 'Chat sin propietario', body: 'Ayuda', channel: 'chat', assignedTo: '' });
inbox.state.activeId = unassigned.id; inbox.renderAll();
click(q('[data-inbox="create-ticket"]'));
if (f.source.value !== 'Chat' || f.owner.value !== 'Sin asignar') fail('chat/unassigned defaults');
click(q('#ct-panel [data-ct="cancel"]'));
const orphan = Conv.createConversation({ subject: 'Sin contacto', body: 'Ayuda', channel: 'email' });
inbox.state.activeId = orphan.id; inbox.renderAll();
if (!q('[data-inbox="create-ticket"]').disabled || !text($('inbox-ticket-hint'))) fail('missing contact disabled with hint');
click(q('[data-inbox="create-ticket"]'));
if ($('ct-panel').classList.contains('is-open')) fail('missing contact cannot open');
if (networkCalls) fail('smoke must remain local');
console.log('[inbox-create-ticket] OK: prefill, associations, pipeline, timelines, thread, toast, duplicate submit and missing contact');
process.exit(0);
