import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const dom = new JSDOM(readFileSync(new URL('../reports/index.html', import.meta.url), 'utf8'), {url: 'http://localhost/reports/?dash=marketing'});
for (const k of ['window','document','localStorage','HTMLElement','location']) globalThis[k] = dom.window[k];
dom.window.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
dom.window.HTMLDialogElement.prototype.close = function() { this.dispatchEvent(new dom.window.Event('close')); };
let copied;
Object.defineProperty(globalThis, 'navigator', {value: {clipboard: {writeText: async text => {copied = text;}}}, configurable:true});
const config = {source:'deals',measure:'count',dimension:'stage',visualization:'kpi'};
localStorage.setItem('crm:custom-reports:v1', JSON.stringify([{id:'custom', name:'Rango', pinned:true, config}]));
const R = await import('../src/reports.js');
const {createDashboardStore} = await import('../src/dashboards.js');
await R.customReports.ready;
const click = selector => { const el = document.querySelector(selector); assert.ok(el, selector); el.click(); };
assert.equal(R.state.dash,'marketing');
click('[data-action="create-dashboard"]');
let form = document.querySelector('dialog form'); form.elements.name.value = 'Prueba'; form.dispatchEvent(new dom.window.Event('submit',{cancelable:true}));
const created = R.state.dash;
assert.equal(document.querySelectorAll('#grid [data-card-key]').length,0);
assert.equal(createDashboardStore().get(created).name,'Prueba');
click('[data-action="add-report"]'); click('#restore-reports button');
assert.equal(document.querySelectorAll('#grid [data-card-key]').length,1);
click('#grid [data-action="remove"]');
R.render(); assert.equal(document.querySelectorAll('#grid [data-card-key]').length,0);
assert.equal(createDashboardStore().get(created).hidden.length,5);
click('[data-action="clone"]');
assert.notEqual(R.state.dash,created);
assert.equal(new URL(location.href).searchParams.get('dash'),R.state.dash);
assert.deepEqual(createDashboardStore().get(R.state.dash).hidden,R.dashboards.get(created).hidden);
click('[data-action="share"]'); await Promise.resolve(); assert.equal(copied,location.href);
click('[data-dash="ventas"]');
click('[data-range="7"]');
const pins = document.querySelector('#grid + .grid');
const short = pins.querySelector('.kpi__value')?.textContent;
click('[data-range="365"]');
assert.notEqual(pins.querySelector('.kpi__value')?.textContent,short);
click('[data-dash="marketing"]'); assert.equal(pins.children.length,0);
click('[data-dash="ventas"]'); click('#grid + .grid [data-pin]');
assert.equal(createDashboardStore().get('ventas').pins.length,0);
assert.equal(document.querySelector('[data-action="export"]'),null);
click('[data-action="rename-dashboard"]');
form = document.querySelector('dialog form'); form.elements.name.value = 'Ventas renombradas'; form.dispatchEvent(new dom.window.Event('submit',{cancelable:true}));
assert.equal(createDashboardStore().get('ventas').name,'Ventas renombradas');
const search = document.querySelector('[data-dash-search]'); search.value = 'renombradas'; search.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.equal(document.querySelectorAll('[data-dash]:not([hidden])').length,1);
click('[data-action="delete-dashboard"]'); document.querySelector('dialog form').dispatchEvent(new dom.window.Event('submit',{cancelable:true}));
assert.equal(createDashboardStore().get('ventas'),undefined);
const isolated = createDashboardStore({getItem:()=>null,setItem:()=>{}});
isolated.remove('ventas'); isolated.remove('marketing'); assert.throws(()=>isolated.remove('servicio'));
console.log('OK: selector URL, crear, restaurar, ocultar persistente, clonar, compartir, pins por panel y rango.');
