import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const dom = new JSDOM('<body class="app"><aside id="sidenav"></aside><header id="topbar"></header><main id="list-root"></main><div id="scrim"></div></body>', { url: 'http://localhost/contacts/' });
for (const key of ['window', 'document', 'localStorage', 'FormData', 'HTMLElement', 'location', 'URL', 'Blob']) globalThis[key] = dom.window[key];
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const data = await import('../src/data.js');
await import('../src/contacts.js');
const tick = () => new Promise(r => setTimeout(r, 40));
const $ = s => document.querySelector(s);
const cb = $('.row-check');
const id = Number(cb.dataset.id);
cb.checked = true; cb.dispatchEvent(new window.Event('change', { bubbles: true }));
$(`[data-preview="${id}"]`).click(); await tick();
const table = $('tbody');
const original = table.innerHTML;
const scroll = table.closest('.table-wrap') || table.parentElement;
scroll.scrollTop = 180;
$('[data-pv="note"]').click(); await tick();
$('#log-notes').value = 'Nota de prueba desde la vista previa';
$('[data-confirm="logact"]').click();
assert.ok(data.activitiesFor('contacts', id).some(a => a.text === 'Nota de prueba desde la vista previa'));
assert.match($('#pv-extra').textContent, /Nota de prueba/);
assert.equal(location.pathname, '/contacts/');
assert.equal(table.innerHTML, original);
assert.equal(scroll.scrollTop, 180);
assert.equal($(`.row-check[data-id="${id}"]`).checked, true);
$('[data-pv="task"]').click(); await tick();
$('#tf-name').value = 'Tarea de prueba';
$('[data-confirm="task-save"]').click();
assert.ok(data.allTasks().some(t => t.name === 'Tarea de prueba' && Number(t.contactId) === id));
assert.match($('#pv-extra').textContent, /Tarea de prueba/);
$('[data-pv="meeting"]').click(); await tick();
$('#log-title').value = 'Reunión de prueba';
$('[data-confirm="logact"]').click();
assert.ok(data.activitiesFor('contacts', id).some(a => a.extra?.title === 'Reunión de prueba'));
assert.match($('#pv-extra').textContent, /Reunión de prueba/);
$('[data-pv="call"]').click(); await tick();
$('.callmenu [data-log]').click(); await tick();
$('#log-notes').value = 'Llamada de prueba';
$('[data-confirm="logact"]').click();
assert.ok(data.activitiesFor('contacts', id).some(a => a.type === 'call' && a.text === 'Llamada de prueba'));
$('[data-pv="more"]').click(); await tick();
$('[data-log-kind="email"]').click();
$('#log-title').value = 'Correo registrado';
$('[data-confirm="logact"]').click();
assert.ok(data.activitiesFor('contacts', id).some(a => a.extra?.subject === 'Correo registrado'));
$('[data-pv="email"]').click(); await tick();
assert.ok($('.compose'));
assert.equal(location.pathname, '/contacts/');
assert.equal(table.innerHTML, original);
const { createPreviewActions } = await import('../src/preview-actions.js');
const { taskLinksTo } = await import('../src/task-associations.js');
for (const type of ['companies', 'deals', 'tickets']) {
  const rec = data.ALL[type]()[0];
  const actions = createPreviewActions({ type, singular: type, refresh() {} });
  await actions.open('note', rec);
  $('#log-notes').value = `Nota ${type}`;
  $('[data-confirm="logact"]').click();
  assert.ok(data.activitiesFor(type, rec.id).some(a => a.text === `Nota ${type}`));
  await actions.open('task', rec);
  $('#tf-name').value = `Tarea ${type}`;
  $('[data-confirm="task-save"]').click();
  assert.ok(data.allTasks().some(t => t.name === `Tarea ${type}` && taskLinksTo(t, type, rec.id)));
}
console.log('Preview actions: note, task, meeting, logged call, composer, associations and list state OK');
dom.window.close();
