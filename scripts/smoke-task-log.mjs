import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const dom = new JSDOM('<body class="app"><aside id="sidenav"></aside><header id="topbar"></header><main id="list-root"></main><div id="scrim"></div></body>', { url: 'http://localhost/tasks/' });
for (const key of ['window', 'document', 'localStorage', 'location', 'HTMLElement', 'FormData', 'URL', 'Blob']) globalThis[key] = key === 'window' ? dom.window : dom.window[key];
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const data = await import('../src/data.js');
const { completeTaskWithLog, mountQueueBar, startQueue, activeQueue, setNavigator } = await import('../src/task-queue.js');
const { mountSubtasks } = await import('../src/subtasks.js');
await import('../src/tasks.js');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const modal = () => document.getElementById('task-log-modal');
const toggle = cb => { cb.checked = true; cb.dispatchEvent(new dom.window.Event('change', { bubbles: true })); };
for (const type of ['Llamada', 'Correo']) {
  const cb = [...document.querySelectorAll('.task-done')].find(el => !el.checked);
  const task = data.findRecord('tasks', cb.dataset.id);
  data.setField('tasks', task.id, 'type', type);
  data.setField('tasks', task.id, 'status', 'waiting');
  const before = data.activitiesFor('contacts', task.contactId).length;
  toggle(cb);
  assert.ok(modal());
  assert.ok(modal().textContent.includes(task.contact));
  assert.equal(cb.checked, false);
  document.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  await tick();
  assert.equal(data.findRecord('tasks', task.id).status, 'waiting');
  assert.equal(data.activitiesFor('contacts', task.contactId).length, before);
  assert.equal(cb.disabled, false);
  toggle(cb);
  const pending = completeTaskWithLog(task.id);
  assert.equal(document.querySelectorAll('#task-log-modal').length, 1);
  modal().querySelector('#log-direction').value = 'Entrante';
  modal().querySelector('#log-notes').value = `Notas de ${type}`;
  if (type === 'Llamada') {
    modal().querySelector('#log-outcome').value = 'Conectado';
    modal().querySelector('#log-duration').value = '30';
  } else modal().querySelector('#log-title').value = 'Correo recibido';
  modal().querySelector('[data-confirm="logact"]').click();
  assert.equal(await pending, true);
  await tick();
  assert.equal(data.findRecord('tasks', task.id).status, 'done');
  assert.ok(data.findRecord('tasks', task.id).completedAt);
  const events = data.activitiesFor('contacts', task.contactId);
  const activity = events.find(e => e.extra?.notes === `Notas de ${type}`);
  assert.equal(activity.type, type === 'Llamada' ? 'call' : 'email');
  assert.equal(activity.extra.direction, 'Entrante');
  if (type === 'Llamada') { assert.equal(activity.extra.outcome, 'Conectado'); assert.equal(activity.extra.durationMin, 30); }
  else assert.equal(activity.extra.subject, 'Correo recibido');
  assert.ok(events.some(e => e.type === 'system' && e.extra?.task === task.id));
  const count = events.length;
  assert.equal(completeTaskWithLog(task.id), true);
  assert.equal(data.activitiesFor('contacts', task.contactId).length, count);
}
const general = data.addRecord('tasks', { name: 'General', type: 'Tarea', status: 'todo' });
assert.equal(completeTaskWithLog(general.id), true);
assert.equal(modal(), null);
const direct = data.addRecord('tasks', { name: 'General en cola', type: 'Tarea', status: 'todo' });
startQueue([direct.id]);
setNavigator(() => {});
const bar = document.createElement('div');
document.body.append(bar);
mountQueueBar({ container: bar });
bar.querySelector('[data-tq="complete"]').click();
assert.equal(modal(), null);
assert.equal(data.findRecord('tasks', direct.id).status, 'done');
assert.equal(activeQueue().index, 1);
const parent = data.addRecord('tasks', { name: 'Madre llamada', type: 'Llamada', status: 'todo', contactId: 1 });
const child = data.addRecord('tasks', { name: 'Subtarea', type: 'Correo', status: 'todo', parentId: parent.id });
const panel = document.createElement('div');
document.body.append(panel);
mountSubtasks(panel, parent.id);
toggle(panel.querySelector('[data-subtask]'));
assert.equal(data.findRecord('tasks', child.id).status, 'done');
assert.equal(modal(), null);
panel.querySelector('[data-complete-parent]').click();
assert.ok(modal());
modal().querySelector('[data-close]').click();
await tick();
assert.equal(data.findRecord('tasks', parent.id).status, 'todo');
panel.querySelector('[data-complete-parent]').click();
modal().querySelector('[data-confirm="logact"]').click();
await tick();
assert.equal(data.findRecord('tasks', parent.id).status, 'done');
console.log('PASS: lista llamada/correo, cancelar/Escape, asociaciones, resultado/dirección/duración, sin duplicados, generales y subtareas directas, madre con registro.');
dom.window.close();
process.exit(0);
