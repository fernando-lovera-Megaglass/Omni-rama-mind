// Local only: no env file and no remote writes.
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const dom = new JSDOM('<main><button data-action="add-report">Añadir informe</button><div id="grid"></div></main>', { url: 'http://localhost/reports/' });
for (const key of ['window', 'document', 'localStorage', 'location', 'HTMLElement']) globalThis[key] = dom.window[key];
const { mountReportBuilder } = await import('../src/report-builder.js');
const { createReportStore, aggregateReport } = await import('../src/custom-reports.js');
const store = createReportStore(null, localStorage);
const mount = () => mountReportBuilder({ root: document.querySelector('main'), dashboard: document.querySelector('#grid'), store });
let ui = mount(); await ui.ready; ui.open();
document.querySelector('[data-create]').click();
const form = document.querySelector('form');
assert.equal(form.elements.name.value, 'Negocios por etapa (barras)');
assert.equal(form.elements.source.value, 'deals');
assert.equal(form.elements.dimension.value, 'stage');
assert.equal(form.elements.visualization.value, 'bars');
assert.ok(document.querySelector('.custom-bar'));
form.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
await new Promise(resolve => setTimeout(resolve, 0));
assert.match(document.querySelector('[data-list]').textContent, /Negocios por etapa \(barras\)/);
assert.equal((await store.list()).length, 1);
document.querySelector('[data-pin]').click();
await new Promise(resolve => setTimeout(resolve, 0));
assert.equal((await store.list())[0].pinned, true);
assert.match(document.querySelector('.card--report').textContent, /Negocios por etapa/);
document.querySelector('main').innerHTML = '<div id="grid"></div>';
ui = mount(); await ui.ready;
assert.ok(document.querySelector('.card--report'), 'pinned card survives remount');
ui.open();
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const search = document.querySelector('[data-search]');
search.value = 'no existe'; search.dispatchEvent(new dom.window.Event('input'));
assert.match(document.querySelector('[data-list]').textContent, /No hay informes que coincidan/);
assert.equal(document.querySelector('[data-empty]'), null);
search.value = ''; search.dispatchEvent(new dom.window.Event('input'));
document.querySelector('[data-duplicate]').click(); await tick();
let saved = await store.list();
assert.equal(saved.length, 2);
assert.notEqual(saved[0].id, saved[1].id);
assert.deepEqual(saved[0].config, saved[1].config);
assert.equal(saved[0].pinned, false);
document.querySelector('[data-rename]').click();
document.querySelector('form').elements.name.value = 'Informe renombrado';
document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true })); await tick();
assert.equal((await store.list())[0].name, 'Informe renombrado');
document.querySelector('[data-view]').click();
assert.match(document.querySelector('.custom-library h2').textContent, /Informe renombrado/);
document.querySelector('[data-back]').click();
for (let i = 0; i < 2; i++) {
  document.querySelector('[data-delete]').click();
  document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true })); await tick();
}
assert.equal((await store.list()).length, 0);
assert.ok(document.querySelector('[data-empty] svg'));
assert.equal(document.querySelector('.card--report'), null);
const config = { source: 'deals', measure: 'average', dimension: 'owner', visualization: 'kpi' };
assert.equal(aggregateReport(config, [{ owner: 'A', amount: 10 }, { owner: 'A', amount: 20 }, { owner: 'B', amount: 90 }, { owner: 'B', amount: null }]).total, 40);
assert.throws(() => aggregateReport({ ...config, source: 'contacts' }, []));
// Failed writes must not appear as successful saves in the library.
document.querySelector('main').innerHTML = '<div id="grid"></div>';
ui = mountReportBuilder({ root: document.querySelector('main'), dashboard: document.querySelector('#grid'), store: { list: async () => [], save: async () => { throw new Error('Error de conexión'); } } });
await ui.ready; ui.open(); document.querySelector('[data-create]').click();
document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
await new Promise(resolve => setTimeout(resolve, 0));
assert.match(document.querySelector('[data-status]').textContent, /No se pudo guardar/);
assert.equal(document.querySelector('[type=submit]').disabled, false);
document.querySelector('main').innerHTML = '<div id="grid"></div>';
ui = mountReportBuilder({ root: document.querySelector('main'), dashboard: document.querySelector('#grid'), store: { list: async () => { throw new Error('Sin conexión'); } } });
await ui.ready;
assert.equal(document.querySelector('[data-empty]'), null, 'load failure is not an empty library');
assert.ok(document.querySelector('[data-retry]'));
assert.match(document.querySelector('[data-status]').textContent, /No se pudieron cargar/);
console.log('OK: crear Negocios por etapa (barras), guardar, biblioteca, anclar, recargar, buscar, abrir, duplicar, renombrar, eliminar, vacío, promedio y error de escritura.');
