import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const memory = new Map();
globalThis.localStorage = { getItem: k => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, String(v)), removeItem: k => memory.delete(k), key: i => [...memory.keys()][i] ?? null, get length() { return memory.size; } };
const dom = new JSDOM('<body data-type="contacts"><aside id="sidenav"></aside><header id="topbar"></header><main id="record-root"></main><div id="scrim"></div>', { url: 'http://localhost/contacts/record/?id=1' });
for (const key of ['window', 'document', 'location', 'HTMLElement', 'FormData']) globalThis[key] = key === 'window' ? dom.window : dom.window[key];
dom.window.HTMLElement.prototype.scrollIntoView = function () {};
const tick = () => new Promise(resolve => setTimeout(resolve, 20));
await import('../src/record.js');
document.querySelector('[data-tab="activity"]').click();
const noteForm = document.querySelector('#note-form');
noteForm.querySelector('textarea').value = 'Nota para smoke de comentarios';
noteForm.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
await tick();
let thread = document.querySelector('#rec-timeline .activity-comments');
thread.querySelector('[data-comment-toggle]').click();
await tick();
assert.equal(thread.querySelector('[data-comment-thread]').hidden, false);
thread.querySelector('textarea').value = 'Comentario persistido <script>alert(1)</script>';
thread.querySelector('form').dispatchEvent(new dom.window.Event('submit', { cancelable: true }));
await tick();
assert.equal(thread.querySelector('[data-comment-count]').textContent, '(1)');
assert.ok(thread.querySelector('.avatar'));
assert.equal(thread.querySelector('script'), null);
// Reload the record module and rebuild the page from persisted localStorage.
await import('../src/record.js?reload-comments');
document.querySelector('[data-tab="activity"]').click();
await tick();
thread = document.querySelector('#rec-timeline .activity-comments');
thread.querySelector('[data-comment-toggle]').click();
await tick();
assert.equal(thread.querySelector('[data-comment-count]').textContent, '(1)');
assert.match(thread.querySelector('[data-comment-list]').textContent, /Comentario persistido/);
assert.ok(thread.querySelector('.avatar'));
console.log('OK: comentar nota, recargar, contador, avatar y texto escapado (persistencia local de demo).');
