document.querySelector('[data-adtab="new"]').click();
assert.equal(document.querySelector('#ad-new-form [name="domain"]').value, 'acme.com');
boot(`http://localhost/companies/record/?id=${company.id}`, 'companies', 'record-root');
await import('../src/record.js?company-enrichment');
assert.ok(document.querySelector('#rec-avatar img'));
boot('http://localhost/companies/', 'companies', 'list-root');
