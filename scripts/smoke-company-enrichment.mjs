import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<body></body>', { url: 'http://localhost', runScripts: 'dangerously' });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.localStorage = dom.window.localStorage;
const data = await import('../src/data.js');
const { companyAvatarHtml } = await import('../src/owner.js');
const company = data.addRecord('companies', { name: 'Acme Company', domain: 'acme.com' });
let saved = () => data.findRecord('companies', company.id);
assert.equal(saved().website, 'https://acme.com');
assert.equal(saved().logoUrl, 'https://www.google.com/s2/favicons?domain=acme.com&sz=128');
assert.deepEqual(data.dbColumnFor('companies', 'logoUrl'), { column: 'extra->>logoUrl', json: true });
document.body.innerHTML = companyAvatarHtml(saved(), 'lg');
assert.ok(document.querySelector('img'));
document.querySelector('img').dispatchEvent(new dom.window.Event('error'));
assert.equal(document.querySelector('img'), null);
assert.equal(document.body.textContent, 'AC');
data.setField('companies', company.id, 'website', 'https://custom.example/path');
data.setField('companies', company.id, 'domain', 'https://www.new-acme.com/path');
assert.ok(saved().logoUrl.includes('domain=new-acme.com&'));
assert.equal(saved().website, 'https://custom.example/path');
data.setField('companies', company.id, 'domain', '');
assert.equal(saved().logoUrl, '');
assert.ok(!companyAvatarHtml(saved()).includes('<img'));
data.setField('companies', company.id, 'website', '');
data.setField('companies', company.id, 'domain', 'acme.com');
assert.equal(saved().website, 'https://acme.com');
assert.equal(data.companyDomainPrefill({ email: 'Person@ACME.com' }), 'acme.com');
for (const domain of data.FREE_EMAIL_DOMAINS) assert.equal(data.companyDomainPrefill({ email: `person@${domain}` }), '');
assert.equal(data.companyDomainPrefill({ email: 'invalid' }), '');
assert.equal(data.companyDomainPrefill({}), '');
assert.equal(data.companyDomainEnrichment({ domain: 'acme.com', extra: { website: 'https://custom.example' } }).website, undefined);
console.log('company enrichment: passed');
function boot(url, type, root) {
  const page = new JSDOM(`<body class="app" data-type="${type}"><aside id="sidenav"></aside><header id="topbar"></header><main id="${root}"></main><div id="scrim"></div></body>`, { url });
  globalThis.window = page.window;
  globalThis.document = page.window.document;
  globalThis.location = page.window.location;
  globalThis.HTMLElement = page.window.HTMLElement;
  globalThis.FormData = page.window.FormData;
  Object.defineProperty(globalThis, 'navigator', { value: { clipboard: { writeText() {} } }, configurable: true });
  return page;
}
