data.saveDealPipelineDefs(defs);
let pending = changeDealStage(d, 'lost');
let modal = $('deal-close-modal');
assert(modal);
const submit = () => modal.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
