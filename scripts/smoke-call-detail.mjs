// Local-only regression coverage for the call drawer and recording lifecycle.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const dom = new JSDOM('<body class="app"><aside id="sidenav"></aside><header id="topbar"></header><main id="calls-root"></main><div id="scrim"></div></body>', { url: 'http://localhost/calls/' });
for (const key of ['window', 'document', 'localStorage', 'location', 'HTMLElement', 'CustomEvent', 'FormData', 'Option', 'MutationObserver']) globalThis[key] = dom.window[key];
const data = await import('../src/data.js');
const { openCallDetail } = await import('../src/call-detail.js');
data.addActivity({ type: 'call', recordType: 'contacts', recordId: 1, text: 'Original', when: Date.now(), extra: { outcome: 'Sin respuesta', direction: 'Entrante', durationMin: 3 } });
const activity = data.activitiesFor('contacts', 1)[0];
const row = { id: `log-${activity.id}`, source: 'log', activity, title: 'Llamada de prueba', when: activity.when, direction: 'inbound', status: 'Sin respuesta', notes: 'Original' };
await import('../src/calls.js');
await new Promise(resolve => setTimeout(resolve, 30));
const indexRow = document.querySelector(`[data-callrow="${row.id}"]`);
assert.ok(indexRow);
indexRow.click();
assert.equal(location.pathname, '/calls/');
document.querySelector('#call-detail-outcome').value = 'Conectado';
document.querySelector('[data-detail-save]').click();
await new Promise(resolve => setTimeout(resolve, 0));
assert.match(document.querySelector(`[data-callrow="${row.id}"]`).textContent, /Conectado/);
document.querySelector('[data-detail-close]').click();
let refreshed = 0;
const drawer = openCallDetail(row, { contactName: 'Contacto', duration: '3 minutos', onSaved: () => { refreshed++; } });
assert.match(drawer.querySelector('a').href, /contacts\/record\/\?id=1/);
drawer.querySelector('select').value = 'Conectado';
drawer.querySelector('textarea').value = 'Notas completas\n<texto>';
drawer.querySelector('[data-detail-save]').click();
assert.equal(drawer.querySelector('textarea').disabled, true);
await new Promise(resolve => setTimeout(resolve, 0));
assert.equal(refreshed, 1);
const fresh = await import('../src/data.js?call-detail-reload');
const saved = fresh.activitiesFor('contacts', 1)[0];
assert.equal(saved.extra.outcome, 'Conectado');
assert.equal(saved.text, 'Notas completas\n<texto>');
assert.equal(saved.extra.durationMin, 3);
assert.equal(saved.extra.direction, 'Entrante');
drawer.querySelector('[data-detail-close]').click();
assert.equal(document.querySelector('#call-detail'), null);

// Open the actual contact timeline against the persisted activity.
dom.window.history.replaceState({}, '', '/contacts/record/?id=1');
document.body.dataset.type = 'contacts';
document.getElementById('calls-root').id = 'record-root';
await import('../src/record.js');
assert.match(document.querySelector('#rec-timeline').textContent, /Conectado/);
assert.match(document.querySelector('#rec-timeline').textContent, /Notas completas/);

const twilio = openCallDetail({ source: 'twilio', title: 'Grabada', when: Date.now(), recording: true, callSid: 'CA-test', transcript: '<Transcripción completa>' });
assert.equal(twilio.querySelector('[data-detail-transcript]').textContent, '<Transcripción completa>');
assert.equal(twilio.querySelector('[data-detail-save]'), null);
let played = 0, paused = 0, revoked = [];
dom.window.HTMLMediaElement.prototype.play = function () { played++; return Promise.resolve(); };
dom.window.HTMLMediaElement.prototype.pause = function () { paused++; };
dom.window.HTMLMediaElement.prototype.load = function () {};
URL.createObjectURL = () => 'blob:local-recording';
URL.revokeObjectURL = url => revoked.push(url);
let resolveDownload;
globalThis.fetch = () => new Promise(resolve => { resolveDownload = () => resolve({ ok: true, blob: async () => new Blob(['audio']) }); });
// Keep the production player; replace only its service client with an offline fixture.
let source = await readFile(new URL('../src/call.js', import.meta.url), 'utf8');
source = source.replace("import { supabase } from './supabaseClient.js';", "const supabase = { auth: { getSession: async () => ({ data: {} }) }, supabaseUrl: 'https://local.invalid', supabaseKey: 'test' };");
source = source.replace(/from '(\.\/[^']+)'/g, (_, path) => `from '${new URL('../src/' + path.slice(2), import.meta.url).href}'`);
const { playRecording } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const pending = playRecording(twilio.querySelector('[data-detail-play]'), 'CA-test');
await new Promise(resolve => setTimeout(resolve, 0));
resolveDownload();
await pending;
assert.equal(played, 1);
assert.equal(twilio.querySelector('audio').controls, true);
twilio.querySelector('[data-detail-close]').click();
assert.equal(paused, 1);
assert.deepEqual(revoked, ['blob:local-recording']);
const closing = openCallDetail({ source: 'twilio', title: 'Pendiente', when: Date.now(), recording: true });
const late = playRecording(closing.querySelector('[data-detail-play]'), 'CA-late');
await new Promise(resolve => setTimeout(resolve, 0));
closing.querySelector('[data-detail-close]').click();
resolveDownload();
await late;
assert.equal(played, 1, 'Closed drawer must never start playback');
assert.equal(revoked.length, 2);
console.log('Call detail: persisted edit, metadata, association, transcript, playback and close-during-download passed.');
dom.window.close();
