// Local DOM integration smoke: published workflow, three selected contacts, one active run.
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const fail = (message) => { throw new Error(message); };
const wait = (ms) => new Promise(resolve => setTimeout(resolve, ms));
const mem = {};
globalThis.localStorage = { getItem: (k) => (k in mem ? mem[k] : null), setItem: (k, v) => { mem[k] = String(v); }, removeItem: (k) => { delete mem[k]; }, key: (i) => Object.keys(mem)[i] ?? null, get length() { return Object.keys(mem).length; }, clear: () => { Object.keys(mem).forEach((k) => delete mem[k]); } };
function useDom(html, url) {
  const dom = new JSDOM(html, { url, pretendToBeVisual: true });
  globalThis.window = dom.window;
  globalThis.document = dom.window.document;
  globalThis.location = dom.window.location;
  globalThis.history = dom.window.history;
  globalThis.HTMLElement = dom.window.HTMLElement;
  globalThis.Event = dom.window.Event;
  globalThis.CustomEvent = dom.window.CustomEvent;
  globalThis.KeyboardEvent = dom.window.KeyboardEvent;
  globalThis.FormData = dom.window.FormData;
  globalThis.URL = dom.window.URL;
  globalThis.Blob = dom.window.Blob;
  dom.window.HTMLElement.prototype.scrollIntoView = function () {};
  dom.window.confirm = () => true;
  dom.window.prompt = (q, d) => d;
  return dom;
}
Object.defineProperty(globalThis, 'navigator', { value: { clipboard: { writeText() {} } }, configurable: true });
const $ = (id) => document.getElementById(id);
const q = (sel) => document.querySelector(sel);
const qa = (sel) => [...document.querySelectorAll(sel)];
const text = (el) => (el ? el.textContent.replace(/\s+/g, ' ').trim() : '');
const click = (el) => { if (!el) fail('missing element to click'); el.dispatchEvent(new window.MouseEvent('click', { bubbles: true, cancelable: true })); };
const change = (el, v) => { if (v !== undefined) el.value = v; el.dispatchEvent(new window.Event('change', { bubbles: true })); };
const toastText = () => text($('toast'));


useDom('<body class="app"><aside id="sidenav"></aside><header id="topbar"></header><main id="list-root"></main><div id="scrim"></div></body>', 'http://localhost/contacts/');
const data = await import('../src/data.js');
const W = await import('../src/workflows-data.js');
const E = await import('../src/workflow-engine.js');
await Promise.all([W.ready, E.ready]);
assert.equal(E.runsLive(), false);
const wf = W.createWorkflow({ name: 'Bulk smoke published', objectType: 'contacts', actions: [{ type: 'delay', config: { amount: 2, unit: 'days' } }] });
W.markPublished(wf.id);
const draft = W.createWorkflow({ name: 'Excluded draft', objectType: 'contacts' });
const company = W.createWorkflow({ name: 'Excluded company', objectType: 'companies' });
W.markPublished(company.id);
const second = W.createWorkflow({ name: 'Another published workflow', objectType: 'contacts', actions: [{ type: 'delay', config: { amount: 1, unit: 'days' } }] });
W.markPublished(second.id);
await import('../src/contacts.js');
await wait(30);
const checks = qa('.row-check').slice(0, 3);
assert.equal(checks.length, 3);
const contacts = checks.map(cb => data.allContacts().find(c => Number(c.id) === Number(cb.dataset.id)));
await E.enroll(wf.id, 'contacts', contacts[0]);
for (const c of contacts) { const cb = q(`.row-check[data-id="${c.id}"]`); cb.checked = true; change(cb); }
assert(text($('bulk-count')).includes('3'));
click(q('#bulk .menu > button'));
assert.equal(q('#bulk .menu > button').getAttribute('aria-expanded'), 'true');
click(q('[data-action="bulk-workflow"]'));
await wait(30);
const options = qa('[name="workflow"] option').map(o => o.value);
assert(options.includes(wf.id));
assert(!options.includes(draft.id));
assert(!options.includes(company.id));
change(q('[name="workflow"]'), wf.id);
assert.equal(qa('#bulk-workflow-preview li').filter(li => text(li).includes('Ya inscrito')).length, 1);
change(q('[name="workflow"]'), second.id);
assert.equal(qa('#bulk-workflow-preview li').filter(li => text(li).includes('Ya inscrito')).length, 0);
change(q('[name="workflow"]'), wf.id);
click($('bulk-ok'));
await wait(60);
assert.equal(toastText(), '2 inscritos · 1 ya estaban inscritos');
assert.equal(E.runsOf(wf.id).length, 3);
for (const c of contacts) assert.equal(data.activitiesFor('contacts', c.id).filter(a => a.text.includes('Inscrito en el workflow «Bulk smoke published»')).length, 1);
click(q('[data-action="bulk-workflow"]'));
await wait(30);
change(q('[name="workflow"]'), wf.id);
click($('bulk-ok'));
await wait(60);
assert.equal(toastText(), '0 inscritos · 3 ya estaban inscritos');
assert.equal(E.runsOf(wf.id).length, 3);
useDom('<body class="app app--editor"><main class="wfe-root" id="wfe-root"></main></body>', `http://localhost/automation/editor/?id=${wf.id}`);
await import('../src/workflow-editor.js');
await wait(30);
click(q('[data-we="history"]')); // «Historial del rendimiento» (with the active count) opens the enrolees view
await wait(20);
assert.equal(qa('#wfe-runs tbody tr[data-run]').length, 3);
for (const c of contacts) assert(text($('wfe-runs')).includes(W.recordName('contacts', c)));
E.stopWorkflowChecker();
console.log('[bulk-workflow] OK: 2 new runs, 1 skipped, timelines, editor and duplicate-free retry');
process.exit(0);
