import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const mem = {};
globalThis.localStorage = { getItem: k => mem[k] ?? null, setItem: (k,v) => { mem[k] = String(v); }, removeItem: k => { delete mem[k]; } };
async function load(n) {
  const dom = new JSDOM('<body class="app" data-type="contacts"><aside id="sidenav"></aside><header id="topbar"></header><main id="record-root"></main><div id="scrim"></div></body>', { url: 'http://localhost/contacts/record/?id=3' });
  for (const k of ['window', 'document', 'location', 'HTMLElement', 'FormData']) globalThis[k] = k === 'window' ? dom.window : dom.window[k];
  await import(`../src/record.js?pin-smoke=${n}`);
}
await load(1);
const data = await import('../src/data.js');
data.addActivity({ id: 'pin-old', recordType: 'contacts', recordId: 3, type: 'note', when: 1700000000000, who: 'Tú', text: 'Acuerdos clave' });
data.addActivity({ id: 'pin-new', recordType: 'contacts', recordId: 3, type: 'note', when: 1710000000000, who: 'Tú', text: 'Otra nota' });
await load(2);
const rows = () => [...document.querySelectorAll('#rec-timeline .timeline__item')];
const row = text => rows().find(r => r.querySelector('.timeline__text').textContent === text);
const pin = text => row(text).querySelector('[data-activity-action="pin"]').click();
const pinned = () => document.querySelectorAll('#rec-timeline .timeline__item--pinned');
const order = rows().map(r => r.dataset.ev);
assert(!row('Acuerdos clave').querySelector('.timeline__detail [data-activity-action]'));
pin('Acuerdos clave');
assert.equal(pinned().length, 1);
assert.equal(rows()[0], row('Acuerdos clave'));
assert.match(rows()[0].textContent, /Fijada/);
assert.equal(mem['crm:contacts:3:pinned'], rows()[0].dataset.ev);
await load(3);
assert.equal(rows()[0], row('Acuerdos clave'));
const search = document.getElementById('act-search');
search.value = 'sin coincidencias';
search.dispatchEvent(new window.Event('input', { bubbles: true }));
assert.equal(pinned().length, 1);
assert.equal(rows().length, 1);
search.value = '';
search.dispatchEvent(new window.Event('input', { bubbles: true }));
pin('Otra nota');
assert.equal(pinned().length, 1);
assert.equal(rows()[0], row('Otra nota'));
assert(!row('Acuerdos clave').classList.contains('timeline__item--pinned'));
pin('Otra nota');
assert.equal(pinned().length, 0);
assert.deepEqual(rows().map(r => r.dataset.ev), order);
await load(4);
assert.equal(pinned().length, 0);
assert.deepEqual(rows().map(r => r.dataset.ev), order);
console.log('PASS: pin, reload, filters, replace, unpin and chronological order');
process.exit(0);
