// Local-only acceptance coverage: creation -> list/export -> record/queue -> reload.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { JSDOM } from 'jsdom';
const record = process.argv[2] === 'record';
const mem = JSON.parse(process.env.NOTES_STORAGE || '{}');
const id = process.env.NOTES_ID;
const notes = 'Contexto <img src=x onerror=alert(1)> & "llamada"\nhttps://example.com/preparar\nTercera línea\nCuarta línea';
const dom = new JSDOM(`<body class="app" ${record ? 'data-type="tasks"' : ''}><aside id="sidenav"></aside><header id="topbar"></header><main id="${record ? 'record-root' : 'list-root'}"></main><div id="scrim"></div></body>`, { url: record ? `http://localhost/tasks/record/?id=${id}` : 'http://localhost/tasks/' });
for (const key of ['window', 'document', 'location', 'HTMLElement', 'FormData']) globalThis[key] = key === 'window' ? dom.window : dom.window[key];
globalThis.localStorage = { getItem: k => mem[k] ?? null, setItem: (k, v) => { mem[k] = String(v); }, removeItem: k => { delete mem[k]; } };
dom.window.HTMLElement.prototype.scrollIntoView = () => {};
const $ = s => document.querySelector(s);
const click = el => { assert.ok(el); el.click(); };
const flush = () => new Promise(r => setTimeout(r, 30));
const data = await import('../src/data.js');
const tq = await import('../src/task-queue.js');
assert.equal(data.rowFromDb('tasks', { id: 9999, extra: { notes } }).notes, notes);
if (!record) {
  await import('../src/tasks.js');
  const form = $('#create-form');
  const textarea = form.elements.notes;
  assert.equal(textarea.tagName, 'TEXTAREA');
  assert.equal(textarea.closest('label').previousElementSibling.querySelector('input').name, 'name');
  form.elements.name.value = 'Prueba local de notas';
  textarea.value = notes;
  form.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
  await flush();
  const task = data.allTasks().find(t => t.name === 'Prueba local de notas');
  assert.equal(task.notes, notes);
  assert.equal($('td[data-key="notes"]'), null, 'hidden by default');
  click($('[data-action="columns"]'));
  click($('#col-groups input[data-key="notes"]'));
  click($('#columns-apply'));
  const cell = $(`td[data-key="notes"][data-id="${task.id}"]`);
  assert.ok(cell);
  assert.equal(cell.textContent, notes);
  assert.equal(cell.querySelector('img'), null);
  // Exercise the actual export dialog and generated CSV, including multiline quoting.
  let exported;
  globalThis.URL.createObjectURL = blob => { exported = blob; return 'blob:local-test'; };
  globalThis.URL.revokeObjectURL = () => {};
  dom.window.HTMLAnchorElement.prototype.click = () => {};
  click($('[data-action="export"]'));
  await flush();
  const exportForm = $('#modal-form');
  if (exportForm) exportForm.dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
  else click($('[data-confirm="export"]'));
  await flush();
  assert.ok(exported, 'export generated');
  assert.ok((await exported.text()).includes(notes.replaceAll('"', '""')));
  const result = spawnSync(process.execPath, [import.meta.filename, 'record'], { env: { ...process.env, NOTES_STORAGE: JSON.stringify(mem), NOTES_ID: String(task.id) }, stdio: 'inherit' });
  assert.equal(result.status, 0);
} else {
  tq.startQueue([Number(id)], 'Notas');
  await import('../src/record.js');
  const row = () => $('#rec-props [data-key="notes"]');
  assert.ok(row().textContent.includes(notes));
  assert.equal($('.tq__notes').textContent, notes);
  assert.equal($('.tq__notes img'), null);
  click(row().querySelector('[data-edit-key="notes"]'));
  const editor = row().querySelector('textarea');
  assert.equal(editor.value, notes);
  editor.value = 'Notas editadas\nSegunda línea';
  editor.blur();
  await flush();
  const reloaded = await import('../src/data.js?notes-reload');
  assert.equal(reloaded.findRecord('tasks', id).notes, 'Notas editadas\nSegunda línea');
  assert.equal($('.tq__notes').textContent, 'Notas editadas\nSegunda línea');
  click(row().querySelector('[data-edit-key="notes"]'));
  row().querySelector('textarea').value = '';
  row().querySelector('textarea').blur();
  await flush();
  assert.equal($('.tq__notes'), null);
  const cleared = await import('../src/data.js?notes-cleared');
  assert.equal(cleared.findRecord('tasks', id).notes, '');
}
console.log('Task notes: OK');
