import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
delete process.env.VITE_SUPABASE_URL;
delete process.env.VITE_SUPABASE_ANON_KEY;
const dom = new JSDOM('<main id="preferences"></main>', { url: 'http://localhost/marketing/preferences/' });
for (const k of ['window','document','localStorage','location']) globalThis[k] = dom.window[k];
const data = await import('../src/data.js');
const marketing = await import('../src/marketing-data.js');
const { propertyMap } = await import('../src/properties.js');
const { applyConditions } = await import('../src/filter-query.js');
await marketing.ready;
const contact = data.allContacts().find(c => c.email);
assert.equal(contact.marketingOptOut, 'No');
assert.equal(propertyMap('contacts').marketingOptOut.kind, 'bool');
assert.deepEqual(data.dbColumnFor('contacts', 'marketingOptOut'), { column: 'extra->>marketingOptOut', json: true });
const email = marketing.createEmail({ nombre: 'Prueba de bajas', asunto: 'Prueba', plantilla: 'plain' });
const before = marketing.recipientsOf(email).length;
const test = marketing.sendTest(email.id, contact.email);
assert.ok(test.html.includes(`c=${contact.id}&amp;e=${email.id}`));
assert.ok(!test.html.includes('#unsubscribe'));
location.hash = new URLSearchParams({ c: contact.id, e: email.id }).toString();
await import('../src/marketing-preferences.js');
const submit = () => document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
submit();
assert.equal(data.findRecord('contacts', contact.id).marketingOptOut, 'Sí');
assert.ok(data.findRecord('contacts', contact.id).marketingOptOutAt);
assert.equal(marketing.recipientsOf(email).length, before - 1);
assert.equal(marketing.excludedRecipientsOf(email).length, 1);
const { addSegment } = await import('../src/segments-data.js');
const segment = addSegment({ name: 'Bajas', object: 'contacts', type: 'static', memberIds: [contact.id] });
const segmentEmail = { ...email, destinatarios: { kind: 'segment', id: segment.id } };
assert.equal(marketing.recipientsOf(segmentEmail).length, 0);
assert.equal(marketing.excludedRecipientsOf(segmentEmail).length, 1);
assert.equal(marketing.checklist(segmentEmail)[0].ok, false);
const again = data.activitiesFor('contacts', contact.id).length;
data.setField('contacts', contact.id, 'marketingOptOut', 'Sí');
assert.equal(data.activitiesFor('contacts', contact.id).length, again);
const countMail = () => data.activitiesFor('contacts', contact.id).filter(a => a.extra?.marketingEmailId === email.id && a.type === 'email').length;
assert.equal(marketing.sendEmail(email.id).enviados, before - 1);
assert.equal(countMail(), 0);
submit();
assert.equal(marketing.recipientsOf(email).length, before);
assert.equal(marketing.recipientsOf(segmentEmail).length, 1);
data.setField('contacts', contact.id, 'marketingOptOut', 'Sí');
data.setField('contacts', contact.id, 'marketingOptOut', 'No');
assert.equal(marketing.recipientsOf(email).length, before);
marketing.sendEmail(email.id);
assert.equal(countMail(), 1);
assert.ok(data.activitiesFor('contacts', contact.id).some(a => a.text === 'Se dio de baja de los correos de marketing'));
let expression;
applyConditions({ or(v) { expression = v; return this; } }, 'contacts', [{ key: 'marketingOptOut', op: 'anyof', value: 'No' }]);
assert.ok(expression.includes('is.null'));
applyConditions({ or(v) { expression = v; return this; } }, 'contacts', [{ key: 'marketingOptOut', op: 'noneof', value: 'Sí' }]);
assert.ok(expression.includes('is.null'), 'not opted out includes contacts without stored preference');
location.hash = 'c=invalid';
window.dispatchEvent(new dom.window.Event('hashchange'));
assert.equal(document.querySelector('form'), null);
console.log('Marketing subscriptions: passed');
