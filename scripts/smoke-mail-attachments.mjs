import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transform } from 'esbuild';
import { JSDOM } from 'jsdom';
import { encodeAttachments, validateAttachmentSize, MAX_ATTACHMENT_BYTES } from '../src/mail-attachments.js';
globalThis.window = new JSDOM('').window;
const bytes = Buffer.from('%PDF-1.4\n\x00\xff\x80', 'latin1');
const file = new window.File([bytes], 'prueba ñ.pdf', { type: 'application/pdf' });
const attachments = await encodeAttachments([file]);
assert.deepEqual(Buffer.from(attachments[0].content, 'base64'), bytes);
assert.throws(() => validateAttachmentSize([{ size: MAX_ATTACHMENT_BYTES }]));
const source = readFileSync('supabase/functions/_shared/gmail.ts', 'utf8');
const mimeSource = source.slice(source.indexOf('export const htmlToText'));
const { code } = await transform(`const b64 = s => Buffer.from(s).toString('base64');\n${mimeSource}`, { loader: 'ts', format: 'esm' });
const { buildMime } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const args = { from: 'sender@example.com', to: ['recipient@example.com'], subject: 'PDF', html: '<p>Hola</p>' };
const mime = buildMime({ ...args, attachments });
assert.match(mime, /multipart\/mixed/);
assert.match(mime, /multipart\/alternative/);
assert.match(mime, /Content-Disposition: attachment; filename\*=UTF-8''prueba%20%C3%B1.pdf/);
assert.match(mime, /Content-Type: application\/pdf/);
assert.ok(mime.includes(attachments[0].content));
assert.ok(!buildMime(args).includes('multipart/mixed'));
assert.throws(() => buildMime({ ...args, attachments: [{ ...attachments[0], size: 99 }] }));
assert.throws(() => buildMime({ ...args, attachments: [{ ...attachments[0], name: 'bad\r\nX: injected' }] }));
assert.throws(() => buildMime({ ...args, attachments: [{ ...attachments[0], content: 'invalid!' }] }));
console.log('Attachment bytes, MIME nesting, Unicode name, no-attachment compatibility and invalid input: OK');
