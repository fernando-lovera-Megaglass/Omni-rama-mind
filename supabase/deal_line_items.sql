-- Aplicar con: node scripts/apply-migration.mjs supabase/deal_line_items.sql
-- (o pegando este archivo en el SQL Editor de Supabase).
--
-- No existe una tabla de productos, así que cada línea es simple: nombre + cantidad + precio unitario
-- (en la moneda del negocio). Idempotente: no toca nada si la tabla ya existe.

create table if not exists public.deal_line_items (
  id bigint generated by default as identity primary key,
  deal_id bigint not null,
  name text not null default '',
  quantity numeric not null default 1,
  price numeric not null default 0,
  currency text not null default 'MXN',
  created timestamptz not null default now(),
  extra jsonb not null default '{}'
);
create index if not exists deal_line_items_deal_id_idx on public.deal_line_items (deal_id);

-- Mismo acceso que el resto de tablas de datos: la clave anónima y los usuarios autenticados
-- (la política «anon full access» de datos se mantiene, como en schema.sql y auth.sql).
alter table public.deal_line_items enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'deal_line_items' and policyname = 'anon full access') then
    create policy "anon full access" on public.deal_line_items for all to anon using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'deal_line_items' and policyname = 'authenticated full access') then
    create policy "authenticated full access" on public.deal_line_items for all to authenticated using (true) with check (true);
  end if;
end $$;
