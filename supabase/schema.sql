-- ATENCIÓN: este script BORRA y recrea las 5 tablas. En tu proyecto existen
-- con otra estructura (ids uuid, sin columna extra), incompatible con la app.
-- Están vacías (0 filas, verificado), así que no se pierde ningún dato.

drop table if exists tasks cascade;
drop table if exists tickets cascade;
drop table if exists deals cascade;
drop table if exists contacts cascade;
drop table if exists companies cascade;

-- ============ EMPRESAS ============
create table if not exists companies (
  id bigint generated by default as identity primary key,
  name text not null default '',
  domain text default '',
  phone text default '',
  owner text default '',
  industry text default '',
  city text default '',
  country text default '',
  employees integer,
  revenue numeric,
  lifecycle text default '',
  last_activity timestamptz,
  last_activity_type text default '',
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

-- ============ CONTACTOS ============
create table if not exists contacts (
  id bigint generated by default as identity primary key,
  first text default '',
  last text default '',
  name text not null default '',
  email text default '',
  phone text default '',
  mobilephone text default '',
  owner text default '',
  company_id bigint,
  company text default '',
  status text default '',
  lifecycle text default '',
  city text default '',
  country text default '',
  source text default '',
  job_title text default '',
  customer_type text default '',
  last_activity timestamptz,
  last_activity_type text default '',
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

-- ============ NEGOCIOS ============
create table if not exists deals (
  id bigint generated by default as identity primary key,
  name text not null default '',
  amount numeric default 0,
  stage text default '',
  pipeline text default '',
  close_date timestamptz,
  owner text default '',
  company_id bigint,
  company text default '',
  contact_id bigint,
  priority text default '',
  type text default '',
  last_activity timestamptz,
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

-- ============ TICKETS ============
create table if not exists tickets (
  id bigint generated by default as identity primary key,
  name text not null default '',
  status text default '',
  priority text default '',
  pipeline text default '',
  owner text default '',
  contact_id bigint,
  source text default '',
  description text default '',
  last_activity timestamptz,
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

-- ============ TAREAS ============
create table if not exists tasks (
  id bigint generated by default as identity primary key,
  name text not null default '',
  type text default '',
  status text default '',
  priority text default '',
  owner text default '',
  contact_id bigint,
  contact text default '',
  due timestamptz,
  last_activity timestamptz,
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

-- ============ SEGURIDAD (RLS) ============
-- Acceso abierto con la anon key mientras no haya autenticación.
-- IMPORTANTE: cualquiera con la anon key puede leer/escribir. Antes de
-- producción hay que activar Supabase Auth y restringir estas políticas.
alter table companies enable row level security;
alter table contacts  enable row level security;
alter table deals     enable row level security;
alter table tickets   enable row level security;
alter table tasks     enable row level security;

create policy "anon full access" on companies for all to anon using (true) with check (true);
create policy "anon full access" on contacts  for all to anon using (true) with check (true);
create policy "anon full access" on deals     for all to anon using (true) with check (true);
create policy "anon full access" on tickets   for all to anon using (true) with check (true);
create policy "anon full access" on tasks     for all to anon using (true) with check (true);
