-- Apply before releasing the UI. No production changes are made by the app.
begin;
create table if not exists public.activity_comments (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.activities(id) on delete cascade,
  texto text not null check (length(btrim(texto)) between 1 and 5000),
  autor text not null,
  user_id uuid default auth.uid(),
  fecha timestamptz not null default now()
);
create index if not exists activity_comments_activity_date_idx on public.activity_comments(activity_id, fecha, id);
alter table public.activity_comments enable row level security;
drop policy if exists "read activity comments" on public.activity_comments;
create policy "read activity comments" on public.activity_comments for select to anon, authenticated
using (exists (select 1 from public.activities a where a.id = activity_id));
drop policy if exists "add activity comments" on public.activity_comments;
create policy "add activity comments" on public.activity_comments for insert to anon, authenticated
with check (user_id is not distinct from auth.uid() and exists (select 1 from public.activities a where a.id = activity_id));
grant select, insert on public.activity_comments to anon, authenticated;
grant usage, select on sequence public.activity_comments_id_seq to anon, authenticated;
commit;
