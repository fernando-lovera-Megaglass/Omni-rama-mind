-- Omni CRM · Pipelines y etapas en Supabase (fuera de localStorage) + los 8 pipelines reales de negocios
-- Aplicar con: node scripts/apply-migration.mjs supabase/pipelines.sql
-- (o pegando este archivo en el SQL Editor de Supabase).
--
-- pipelines:        id, objeto (deal | ticket), nombre, orden, descripcion, extra (reglas, automatizaciones,
--                   lógica, etiquetas, acceso e id público del pipeline), unique(objeto, nombre)
-- pipeline_stages:  id, pipeline_id, clave (la que guarda cada negocio en deals.stage), nombre, probabilidad,
--                   orden, descripcion, unique(pipeline_id, clave)
-- La app lee las tablas al arrancar, mueve una sola vez lo que hubiera en localStorage (crm:pipelines:deals)
-- y desde entonces Configuración › Objetos › Negocios › Pipelines escribe aquí. Las etapas cerradas usan
-- siempre las claves won / lost / deleted. Idempotente: no duplica pipelines ni etapas.

create table if not exists public.pipelines (
  id bigint generated by default as identity primary key,
  objeto text not null check (objeto in ('deal', 'ticket')),
  nombre text not null,
  orden integer not null default 0,
  descripcion text not null default '',
  extra jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (objeto, nombre)
);
create table if not exists public.pipeline_stages (
  id bigint generated by default as identity primary key,
  pipeline_id bigint not null references public.pipelines (id) on delete cascade,
  clave text not null,
  nombre text not null,
  probabilidad numeric not null default 0,
  orden integer not null default 0,
  descripcion text not null default '',
  unique (pipeline_id, clave)
);
create index if not exists pipeline_stages_pipeline_id_idx on public.pipeline_stages (pipeline_id);

alter table public.pipelines enable row level security;
alter table public.pipeline_stages enable row level security;
do $$
declare t text;
begin
  foreach t in array array['pipelines', 'pipeline_stages'] loop
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'anon full access') then
      execute format('create policy "anon full access" on public.%I for all to anon using (true) with check (true)', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'authenticated full access') then
      execute format('create policy "authenticated full access" on public.%I for all to authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;

