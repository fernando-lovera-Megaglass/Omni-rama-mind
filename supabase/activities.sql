-- Crea la tabla que alimenta la cronología unificada de cada registro
-- (notas, llamadas, correos, reuniones, tareas e historial de propiedades).
-- No borra ninguna tabla existente.

create table if not exists activities (
  id bigint generated by default as identity primary key,
  type text not null default 'note',
  record_type text not null,
  record_id bigint not null,
  text text default '',
  who text default '',
  occurred_at timestamptz default now(),
  created timestamptz default now(),
  extra jsonb not null default '{}'
);

create index if not exists activities_record_idx on activities (record_type, record_id);

-- ============ SEGURIDAD (RLS) ============
-- Misma política abierta que el resto de tablas mientras no haya autenticación.
alter table activities enable row level security;

create policy "anon full access" on activities for all to anon using (true) with check (true);
