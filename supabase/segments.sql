-- Segmentos (listas) activos y estáticos sobre contactos, empresas, negocios y tickets.
-- `filters` guarda los grupos de condiciones del editor (Y dentro del grupo, O entre grupos);
-- `member_ids` guarda la foto fija de un segmento estático. No borra ninguna tabla existente.

create table if not exists segments (
  id bigint generated by default as identity primary key,
  name text not null default '',
  object text not null default 'contacts',
  type text not null default 'active',          -- 'active' | 'static'
  description text default '',
  folder text default '',
  creator text default '',
  updated_by text default '',
  filters jsonb not null default '[]',
  member_ids jsonb not null default '[]',
  size integer,                                  -- último recuento procesado
  used_in integer not null default 0,
  campaign text default '',
  access jsonb not null default '{}',            -- { "view": "all" | "me" | "teams", "edit": ..., "teams": [] }
  import_id bigint,
  processed_at timestamptz,
  created timestamptz default now(),
  updated timestamptz default now(),
  extra jsonb not null default '{}'
);

create index if not exists segments_object_idx on segments (object);

-- ============ SEGURIDAD (RLS) ============
-- Misma política abierta que el resto de tablas mientras no haya autenticación.
alter table segments enable row level security;

create policy "anon full access" on segments for all to anon using (true) with check (true);
