-- Omni CRM · Un contacto puede pertenecer a varias empresas (contact_companies)
-- Aplicar con: node scripts/apply-migration.mjs supabase/contact_companies.sql
-- (o pegando este archivo en el SQL Editor de Supabase).
--
-- Una fila por asociación contacto ↔ empresa, con su etiqueta («Principal», «Sin etiqueta», «Facturación»…)
-- y is_primary para la empresa principal (la que sigue copiada en contacts.company_id / company por
-- compatibilidad con listas e informes). La app lee la tabla al arrancar, la muestra en la columna
-- «Contacto → Empresas» (principal y «N registros») y en la tarjeta Empresas de la ficha, y la escribe al
-- asociar o cambiar la principal. Idempotente: la tabla y el relleno inicial no duplican nada.

create table if not exists public.contact_companies (
  id bigint generated by default as identity primary key,
  contact_id bigint not null,
  company_id bigint not null,
  label text not null default 'Sin etiqueta',
  is_primary boolean not null default false,
  created timestamptz not null default now(),
  unique (contact_id, company_id)
);
create index if not exists contact_companies_company_id_idx on public.contact_companies (company_id);

-- Mismo acceso que el resto de tablas de datos (schema.sql y auth.sql).
alter table public.contact_companies enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'contact_companies' and policyname = 'anon full access') then
    create policy "anon full access" on public.contact_companies for all to anon using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'contact_companies' and policyname = 'authenticated full access') then
    create policy "authenticated full access" on public.contact_companies for all to authenticated using (true) with check (true);
  end if;
end $$;

-- Relleno inicial desde lo que ya existe: la empresa principal de cada contacto (contacts.company_id)…
insert into public.contact_companies (contact_id, company_id, label, is_primary)
select c.id, c.company_id, 'Principal', true
  from public.contacts c
 where c.company_id is not null
   and exists (select 1 from public.companies k where k.id = c.company_id)
on conflict (contact_id, company_id) do nothing;

-- …y las empresas añadidas a mano desde la ficha (extra.assoc_companies con sus etiquetas).
insert into public.contact_companies (contact_id, company_id, label, is_primary)
select c.id,
       (x.value)::bigint,
       case when coalesce(c.extra->'assoc_labels_companies'->>x.value, 'Sin etiqueta') = 'Principal' then 'Sin etiqueta'
            else coalesce(c.extra->'assoc_labels_companies'->>x.value, 'Sin etiqueta') end,
       false
  from public.contacts c
       cross join lateral jsonb_array_elements_text(c.extra->'assoc_companies') as x(value)
 where jsonb_typeof(c.extra->'assoc_companies') = 'array'
   and x.value ~ '^[0-9]+$'
   and (x.value)::bigint <> coalesce(c.company_id, -1)
   and exists (select 1 from public.companies k where k.id = (x.value)::bigint)
on conflict (contact_id, company_id) do nothing;
