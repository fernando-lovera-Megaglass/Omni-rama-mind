-- Local migration only. One CRM account per Supabase project.
-- Admins are provisioned by a trusted server in auth.users.raw_app_meta_data:
-- {"role":"admin"}. Never use user_metadata or crm:users for authorization.
begin;
create table if not exists public.user_settings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  scope text not null default 'user',
  key text not null,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique (user_id, key)
);
alter table public.user_settings add column if not exists scope text not null default 'user';
alter table public.user_settings alter column user_id set default auth.uid();
create table if not exists public.account_settings (
  scope text not null default 'account' check (scope = 'account'),
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
-- Preserve legacy global rows before removing them from the personal store.
insert into public.account_settings (key, value, updated_at)
select key, value, updated_at from public.user_settings
where user_id = '00000000-0000-0000-0000-000000000000'
on conflict (key) do nothing;
delete from public.user_settings where user_id = '00000000-0000-0000-0000-000000000000';
alter table public.user_settings enable row level security;
alter table public.account_settings enable row level security;
drop policy if exists "anon full access" on public.user_settings;
drop policy if exists "authenticated full access" on public.user_settings;
drop policy if exists personal_settings on public.user_settings;
create policy personal_settings on public.user_settings for all to authenticated
using (user_id = auth.uid() and scope = 'user')
with check (user_id = auth.uid() and scope = 'user');
drop policy if exists account_settings_read on public.account_settings;
create policy account_settings_read on public.account_settings for select to authenticated using (true);
drop policy if exists account_settings_admin on public.account_settings;
create policy account_settings_admin on public.account_settings for all to authenticated
using ((auth.jwt()->'app_metadata'->>'role') = 'admin')
with check ((auth.jwt()->'app_metadata'->>'role') = 'admin');
revoke all on public.user_settings, public.account_settings from anon;
grant select, insert, update, delete on public.user_settings, public.account_settings to authenticated;
grant usage on sequence public.user_settings_id_seq to authenticated;
create or replace function public.settings_updated_at() returns trigger language plpgsql
set search_path = public as $$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists settings_timestamp on public.user_settings;
create trigger settings_timestamp before update on public.user_settings for each row execute function public.settings_updated_at();
drop trigger if exists settings_timestamp on public.account_settings;
create trigger settings_timestamp before update on public.account_settings for each row execute function public.settings_updated_at();
commit;
