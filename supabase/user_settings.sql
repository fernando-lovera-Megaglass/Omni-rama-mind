-- Omni CRM · Ajustes de la interfaz por usuario o globales (user_settings)
-- Aplicar con: node scripts/apply-migration.mjs supabase/user_settings.sql
-- (o pegando este archivo en el SQL Editor de Supabase).
--
-- Una fila por ajuste y usuario: `key` identifica el ajuste (por ejemplo «crm:contacts:cardprops», las
-- propiedades y el orden de la tarjeta «Acerca de» de la ficha) y `value` guarda su JSON. `user_id` es el
-- usuario de Supabase Auth; el uuid cero significa «global» (vale para toda la cuenta). Al leer, el ajuste del
-- usuario gana sobre el global. Idempotente: no toca nada si la tabla ya existe.

create table if not exists public.user_settings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default '00000000-0000-0000-0000-000000000000',
  key text not null,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  unique (user_id, key)
);

-- Mismo acceso que el resto de tablas de datos (schema.sql y auth.sql); la app filtra por usuario.
alter table public.user_settings enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'user_settings' and policyname = 'anon full access') then
    create policy "anon full access" on public.user_settings for all to anon using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'user_settings' and policyname = 'authenticated full access') then
    create policy "authenticated full access" on public.user_settings for all to authenticated using (true) with check (true);
  end if;
end $$;
